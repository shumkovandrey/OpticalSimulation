# Находим поверхность, которую луч пересекает первой
hit = find_best_hit(current_ray, elements)

# Извлекаем геометрическую нормаль к поверхности в точке пересечения
normal = hit.normal

# Проверяем ориентацию нормали (поддержка двусторонних поверхностей):
# Если скалярное произведение положительно, луч падает с внутренней стороны объекта.
# В этом случае разворачиваем нормаль навстречу лучу для корректного расчета угла.
if np.dot(normal, current_ray.direction) > 0:
    normal = -normal

# Вычисляем вектор зеркального отражения
new_dir = current_ray.direction - 2 * np.dot(current_ray.direction, normal) * normal

# Нормализуем полученный вектор
new_dir /= np.linalg.norm(new_dir)
